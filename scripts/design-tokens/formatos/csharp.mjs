/**
 * Tokens.g.cs — parte gerada da classe Kartodromo.Comum.Tokens (o Tokens.cs escrito à mão só tem o Fonte()).
 * - Nomes legados (Texto, Verde, RaioCampo…) com os MESMOS tipos e valores de antes: nenhum pixel muda.
 *   Superficie continua Color.White (há comparações com == que dependem da cor "conhecida").
 * - Tokens.Claro / Tokens.Escuro: os tokens semânticos de cada tema. Tokens.Primitivo: a paleta crua.
 * Todos os campos ficam neste arquivo, com valores literais (a ordem de inicialização entre arquivos parciais não é garantida).
 */
import { AVISO, ehSemantico, ordenar } from './comum.mjs';
import { corParaRgba, nomePascal, numeroDe } from '../ler-tokens.mjs';

const C = 'System.Drawing.Color';

function cor(hex, conhecida) {
  if (conhecida) return `${C}.${conhecida}`;
  const { r, g, b, a } = corParaRgba(hex);
  return a === 255 ? `${C}.FromArgb(${r}, ${g}, ${b})` : `${C}.FromArgb(${a}, ${r}, ${g}, ${b})`;
}

function flutuante(n) {
  return `${Number.isInteger(n) ? n : n}f`;
}

function xmlDoc(texto, recuo) {
  if (!texto) return '';
  const limpo = texto.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  return `${recuo}/// <summary>${limpo}</summary>\n`;
}

/** Uma linha C# para o token (ou null se o tipo não existe no WinForms). */
function membro(t, v, nome, recuo) {
  const doc = xmlDoc(t.descricao + (t.obsoleto ? ` Obsoleto: ${t.obsoleto}.` : ''), recuo);
  let linha;
  switch (t.tipo) {
    case 'color': linha = `public static readonly ${C} ${nome} = ${cor(v, t.kib.csharp?.corConhecida)};`; break;
    case 'dimension': linha = `public const int ${nome} = ${Math.round(numeroDe(v))};`; break;
    case 'fontSize': linha = `public const float ${nome} = ${flutuante(numeroDe(v))};`; break;
    case 'fontWeight': linha = `public const int ${nome} = ${numeroDe(v)};`; break;
    case 'number': linha = `public const float ${nome} = ${flutuante(numeroDe(v))};`; break;
    case 'duration': linha = `public const int ${nome} = ${Math.round(numeroDe(v))}; // ms`; break;
    case 'fontFamily': linha = `public const string ${nome} = "${(Array.isArray(v) ? v[0] : v)}";`; break;
    case 'shadow': linha = `public static readonly Sombra ${nome} = new(${numeroDe(v.offsetX)}, ${numeroDe(v.offsetY)}, ${numeroDe(v.blur)}, ${numeroDe(v.spread)}, ${cor(v.color)});`; break;
    default: return null; // cubicBezier: só web/Android
  }
  return `${doc}${recuo}${linha}`;
}

export function gerarCsharp({ tokens, temas }) {
  const legado = ordenarLegado(tokens.filter((t) => t.legado));
  const primitivos = ordenar(tokens.filter((t) => t.caminho.startsWith('primitivo.cor.')));
  const semanticos = ordenar(tokens.filter(ehSemantico));

  const blocoLegado = legado.map((t) => membro(t, temas.claro.get(t.caminho), t.caminho.split('.').pop(), '    ')).filter(Boolean).join('\n');
  const blocoPrimitivo = primitivos.map((t) => membro({ ...t, descricao: '' }, temas.claro.get(t.caminho), nomePascal(t.caminho.slice('primitivo.cor.'.length)), '        ')).filter(Boolean).join('\n');
  const tema = (nomeTema) => semanticos.map((t) => membro(t, temas[nomeTema].get(t.caminho), nomePascal(t.caminho), '        ')).filter(Boolean).join('\n');

  return `// ${AVISO}
// <auto-generated />
namespace Kartodromo.Comum;

public static partial class Tokens
{
    /// <summary>Sombra de um token de elevação (px).</summary>
    public readonly record struct Sombra(int X, int Y, int Desfoque, int Espalhamento, ${C} Cor);

    // ---------- nomes legados (valores de antes; telas novas usam Tokens.Claro / Tokens.Escuro)
${blocoLegado}

    /// <summary>Paleta crua. Não use direto numa tela: use Tokens.Claro / Tokens.Escuro.</summary>
    public static class Primitivo
    {
${blocoPrimitivo}
    }

    /// <summary>Tema CLARO — operação (Cronometragem, Recepção, admin, relatórios).</summary>
    public static class Claro
    {
${tema('claro')}
    }

    /// <summary>Tema ESCURO — público (totem, telão, site, tablet).</summary>
    public static class Escuro
    {
${tema('escuro')}
    }
}
`;
}

/** Legado na ordem do Tokens.cs original (cores, raios, espaços, tamanhos) para o diff ficar legível. */
function ordenarLegado(lista) {
  const peso = (t) => (t.tipo === 'color' ? 0 : t.caminho.includes('Raio') ? 1 : t.caminho.includes('Espaco') ? 2 : 3);
  return [...lista].sort((a, b) => peso(a) - peso(b));
}
